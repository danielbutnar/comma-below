"""Write post/kaggle-task-descriptions.md from the task definitions in src/build.py.

Each Kaggle task page has an empty Description field; this file holds the text to paste there, the
same as the markdown cell at the top of each task notebook, so the two can't drift apart.
Usage:  uv run --no-project python post/task_descriptions.py
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
import build  # noqa: E402

WRITE_UP = "https://dev.to/danielbutnar/brasov-or-brasov-15-llms-spell-my-city-right-until-you-spell-it-wrong-first-75a"
HEAD = """# Kaggle task descriptions (paste into each task page's Description field)

Each task page shows "This task does not have a description yet." The text below is the markdown cell at
the top of each task notebook (generated by post/task_descriptions.py from src/build.py), plus the
write-up link.
"""


def main():
    parts = [HEAD]
    for slug, t in build.TASKS.items():
        md = build.MARKDOWN.format(title=t["title"], what=t["what"], how=t["how"]).strip()
        body = md.split("\n", 1)[1].strip()  # drop the "# title" line
        parts.append(f"## {t['title']}\nhttps://www.kaggle.com/benchmarks/tasks/danielbutnar/{slug}\n\n"
                     f"{body}\n\nWrite-up: {WRITE_UP}\n")
    out = ROOT / "post" / "kaggle-task-descriptions.md"
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {out.name}: {len(build.TASKS)} tasks")


if __name__ == "__main__":
    main()
